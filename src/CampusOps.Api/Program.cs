using CampusOps.Api.Requests;
using CampusOps.Api.Security;
using CampusOps.Api.ServiceLevels;
using CampusOps.Api.Technicians;
using CampusOps.Api.WorkOrders;
using CampusOps.Core.Assets;
using CampusOps.Core.Common;
using CampusOps.Core.Integrations;
using CampusOps.Core.Inventory;
using CampusOps.Core.Locations;
using CampusOps.Core.Procurement;
using CampusOps.Core.Reporting;
using CampusOps.Core.Requests;
using CampusOps.Core.ServiceLevels;
using CampusOps.Core.Technicians;
using CampusOps.Core.WorkOrders;
using CampusOps.Infrastructure.Assets;
using CampusOps.Infrastructure.Integrations;
using CampusOps.Infrastructure.Inventory;
using CampusOps.Infrastructure.Locations;
using CampusOps.Infrastructure.Procurement;
using CampusOps.Infrastructure.Requests;
using CampusOps.Infrastructure.ServiceLevels;
using CampusOps.Infrastructure.Technicians;
using CampusOps.Infrastructure.WorkOrders;
using Microsoft.AspNetCore.Authentication;

var builder = WebApplication.CreateBuilder(args);
builder.Services.AddOpenApi();
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<DomainExceptionHandler>();
builder.Services.AddAuthentication(SecurityPolicies.Scheme).AddScheme<AuthenticationSchemeOptions, DemoAuthenticationHandler>(SecurityPolicies.Scheme, _ => { });
builder.Services.AddAuthorization(options => { options.AddPolicy(SecurityPolicies.Operations, policy => policy.RequireRole("Dispatcher", "Manager")); options.AddPolicy(SecurityPolicies.Manager, policy => policy.RequireRole("Manager")); });
builder.Services.AddSingleton<CampusAuthorizer>();
builder.Services.AddSingleton<ILocationStore, InMemoryLocationStore>();
builder.Services.AddSingleton<IAssetStore, InMemoryAssetStore>();
builder.Services.AddSingleton<IMaintenanceRequestStore, InMemoryMaintenanceRequestStore>();
builder.Services.AddSingleton<IWorkOrderStore, InMemoryWorkOrderStore>();
builder.Services.AddSingleton<IWorkOrderHistoryStore, InMemoryWorkOrderHistoryStore>();
builder.Services.AddSingleton<ITechnicianStore, InMemoryTechnicianStore>();
builder.Services.AddSingleton<InMemoryPartStore>();
builder.Services.AddSingleton<IPartStore>(provider => provider.GetRequiredService<InMemoryPartStore>());
builder.Services.AddSingleton<IPartReservationStore>(provider => provider.GetRequiredService<InMemoryPartStore>());
builder.Services.AddSingleton<IClock, CampusOps.Core.Common.SystemClock>();
builder.Services.AddSingleton<IServiceLevelStore, InMemoryServiceLevelStore>();
builder.Services.AddSingleton<IVendorStore, InMemoryVendorStore>();
builder.Services.AddSingleton<IPurchaseRequestStore, InMemoryPurchaseRequestStore>();
builder.Services.AddSingleton<IWebhookStore, InMemoryWebhookStore>();
builder.Services.AddSingleton<IIdempotencyStore, InMemoryIdempotencyStore>();
builder.Services.AddSingleton(new ServiceLevelPolicy(new Dictionary<RequestPriority, TimeSpan> { [RequestPriority.Low] = TimeSpan.FromDays(5), [RequestPriority.Normal] = TimeSpan.FromDays(2), [RequestPriority.High] = TimeSpan.FromHours(8), [RequestPriority.Emergency] = TimeSpan.FromHours(1) }));
builder.Services.AddScoped<LocationService>();
builder.Services.AddScoped<AssetService>();
builder.Services.AddScoped<MaintenanceRequestService>();
builder.Services.AddScoped<WorkOrderService>();
builder.Services.AddScoped<AssignmentService>();
builder.Services.AddScoped<WorkOrderHistoryService>();
builder.Services.AddScoped<PartsService>();
builder.Services.AddScoped<ServiceLevelService>();
builder.Services.AddScoped(provider => new ProcurementService(provider.GetRequiredService<IVendorStore>(), provider.GetRequiredService<IPurchaseRequestStore>(), approvalThreshold: 1000m));
builder.Services.AddScoped<WebhookPublisher>();
builder.Services.AddScoped<OperationsReportService>();

var app = builder.Build();
app.UseExceptionHandler();
app.Use(async (context, next) => { var correlationId = context.Request.Headers["X-Correlation-ID"].FirstOrDefault(); if (string.IsNullOrWhiteSpace(correlationId) || correlationId.Length > 100) correlationId = context.TraceIdentifier; context.Response.Headers["X-Correlation-ID"] = correlationId; using (app.Logger.BeginScope(new Dictionary<string, object> { ["CorrelationId"] = correlationId })) await next(context); });
app.UseAuthentication();
app.UseAuthorization();
if (app.Environment.IsDevelopment() || app.Environment.IsEnvironment("Testing")) app.MapOpenApi();
app.MapGet("/health/live", () => Results.Ok(new { status = "healthy" }));
app.MapGet("/health/ready", () => Results.Ok(new { status = "ready", persistence = "in-memory", durable = false, worker = "separate process", note = "SQLite adapters are available; teaching defaults are non-durable." }));
app.MapLocationEndpoints();
app.MapAssetEndpoints();
app.MapMaintenanceRequestEndpoints();
app.MapWorkOrderEndpoints();
app.MapTechnicianEndpoints();
app.MapPartEndpoints();
app.MapServiceLevelEndpoints();
app.MapProcurementEndpoints();
app.MapWebhookEndpoints();
app.MapReportingEndpoints();
app.Run();

